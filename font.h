// Atlas layout: 16 columns x 8 rows of 8x8 cells (chars 0..127), plus a
// fully-white strip in the bottom 8 px rows (sampled for solid cells).
constexpr int ATLAS_W = 128;
constexpr int ATLAS_H = 72;
constexpr int STRIP_Y = 64;

// Fill out (w*h RGBA8, top-left origin, row 0 = top) with the glyph atlas.
inline void buildAtlas(uint8_t* out, int w, int h) {
    for (int i = 0; i < w * h; i++) out[i] = 0;
    auto px = [&](int x, int y) {
        if (x < 0 || y < 0 || x >= w || y >= h) return;
        uint8_t* p = out + (y * w + x) * 4;
        p[0] = p[1] = p[2] = p[3] = 255;
    };
    for (int c = 32; c < 128; c++) {
        const unsigned char* g = FONT5x7[c - 32];
        int cx = (c & 15) * 8;
        int cy = (c >> 4) * 8;
        for (int row = 0; row < 7; row++) {
            unsigned char bits = g[row];
            for (int col = 0; col < 5; col++) {
                if (bits & (1 << (4 - col))) px(cx + 1 + col, cy + 1 + row);
            }
        }
    }
    for (int x = 0; x < w; x++)
        for (int y = STRIP_Y; y < STRIP_Y + 8; y++) px(x, y);
}

// UV rect for a character glyph (v grows downward in the texture).
struct UVRect { float u0, v0, u1, v1; };

inline UVRect glyphUV(int c) {
    if (c < 32 || c > 127) c = ' ';
    int cx = (c & 15) * 8;
    int cy = (c >> 4) * 8;
    return {
        (cx + 1) / (float)ATLAS_W, (cy + 1) / (float)ATLAS_H,
        (cx + 6) / (float)ATLAS_W, (cy + 8) / (float)ATLAS_H
    };
}

// UV rect for a solid (white) fill.
inline UVRect solidUV() {
    return { 0.0f, STRIP_Y / (float)ATLAS_H, 8.0f / (float)ATLAS_W, (STRIP_Y + 8) / (float)ATLAS_H };
}

